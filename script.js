/* ===== LANGUAGE SYSTEM ===== */
let currentLang = localStorage.getItem('voces-lang') || 'en';

function applyLang(lang) {
  document.documentElement.lang = lang;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const v = T[lang][el.dataset.i18n];
    if (v !== undefined) el.textContent = v;
  });

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const v = T[lang][el.dataset.i18nHtml];
    if (v !== undefined) el.innerHTML = v;
  });

  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const v = T[lang][el.dataset.i18nPh];
    if (v !== undefined) el.placeholder = v;
  });

  const lbActive   = document.getElementById('lbActive');
  const lbInactive = document.getElementById('lbInactive');
  const langBtn    = document.getElementById('langBtn');
  if (lang === 'en') {
    lbActive.textContent   = 'EN';
    lbInactive.textContent = 'ES';
    langBtn.setAttribute('aria-label', 'Cambiar a Español');
  } else {
    lbActive.textContent   = 'ES';
    lbInactive.textContent = 'EN';
    langBtn.setAttribute('aria-label', 'Switch to English');
  }

  localStorage.setItem('voces-lang', lang);
  currentLang = lang;
}

document.getElementById('langBtn').addEventListener('click', () => {
  applyLang(currentLang === 'en' ? 'es' : 'en');
});

/* ===== HEADER SCROLL ===== */
const header = document.getElementById('header');
window.addEventListener('scroll', () => {
  header.classList.toggle('scrolled', window.scrollY > 60);
}, { passive: true });

/* ===== MOBILE NAV ===== */
const navToggle = document.getElementById('navToggle');
const navLinks  = document.getElementById('navLinks');

navToggle.addEventListener('click', () => {
  const open = navLinks.classList.toggle('open');
  navToggle.classList.toggle('open', open);
  navToggle.setAttribute('aria-expanded', open);
  document.body.style.overflow = open ? 'hidden' : '';
});

navLinks.querySelectorAll('.nav-link').forEach(link => {
  link.addEventListener('click', () => {
    navLinks.classList.remove('open');
    navToggle.classList.remove('open');
    navToggle.setAttribute('aria-expanded', 'false');
    document.body.style.overflow = '';
  });
});

document.addEventListener('click', e => {
  if (navLinks.classList.contains('open') && !navLinks.contains(e.target) && !navToggle.contains(e.target)) {
    navLinks.classList.remove('open');
    navToggle.classList.remove('open');
    navToggle.setAttribute('aria-expanded', 'false');
    document.body.style.overflow = '';
  }
});

/* ===== SCROLL REVEAL ===== */
const revealObserver = new IntersectionObserver((entries) => {
  entries.forEach(entry => {
    if (entry.isIntersecting) {
      entry.target.classList.add('visible');
      revealObserver.unobserve(entry.target);
    }
  });
}, { threshold: 0.12, rootMargin: '0px 0px -40px 0px' });

document.querySelectorAll('.reveal').forEach(el => revealObserver.observe(el));

/* ===== CONTACT FORM ===== */
const form      = document.getElementById('contactForm');
const submitBtn = document.getElementById('submitBtn');

form.addEventListener('submit', e => {
  e.preventDefault();
  submitBtn.disabled = true;
  submitBtn.textContent = T[currentLang]['form.sending'];

  setTimeout(() => {
    submitBtn.textContent = T[currentLang]['form.sent'];
    submitBtn.style.background = '#2e7d32';
    form.reset();
    setTimeout(() => {
      submitBtn.textContent = T[currentLang]['form.submit'];
      submitBtn.style.background = '';
      submitBtn.disabled = false;
    }, 3500);
  }, 900);
});

/* ===== SMOOTH SCROLL (fallback) ===== */
document.querySelectorAll('a[href^="#"]').forEach(anchor => {
  anchor.addEventListener('click', function(e) {
    const id = this.getAttribute('href');
    if (id === '#') return;
    const target = document.querySelector(id);
    if (target) {
      e.preventDefault();
      target.scrollIntoView({ behavior: 'smooth', block: 'start' });
    }
  });
});

/* ===== INIT LANGUAGE ===== */
applyLang(currentLang);
